namespace de.unika.ipd.grgen.ast
{

	using System.Collections.Generic;

	using FilterAutoGeneratedDeclNode = de.unika.ipd.grgen.ast.decl.executable.FilterAutoGeneratedDeclNode;
	using FilterAutoSuppliedDeclNode = de.unika.ipd.grgen.ast.decl.executable.FilterAutoSuppliedDeclNode;
	using ExprNode = de.unika.ipd.grgen.ast.expr.ExprNode;
	using de.unika.ipd.grgen.ast.util;
	using de.unika.ipd.grgen.ast.util;
	using FilterInvocation = de.unika.ipd.grgen.ir.FilterInvocation;
	using IR = de.unika.ipd.grgen.ir.IR;
	using FilterAutoGenerated = de.unika.ipd.grgen.ir.executable.FilterAutoGenerated;
	using FilterAutoSupplied = de.unika.ipd.grgen.ir.executable.FilterAutoSupplied;
	using Rule = de.unika.ipd.grgen.ir.executable.Rule;
	using Expression = de.unika.ipd.grgen.ir.expr.Expression;

	public class FilterInvocationNode : FilterInvocationBaseNode
	{
		static FilterInvocationNode()
		{
			SetClassName(typeof(FilterInvocationNode), "filter invocation");
		}

		public IdentNode filterUnresolved;
		public FilterAutoGeneratedDeclNode filterAutoGenerated; // filter functions can only be applied on rules
		public FilterAutoSuppliedDeclNode filterAutoSupplied;
		private CollectNode<ExprNode> arguments;

		public FilterInvocationNode(IdentNode iteratedUnresolved, IdentNode filterUnresolved,
				CollectNode<ExprNode> arguments)
			: base(filterUnresolved.Coords, iteratedUnresolved)
		{
			this.filterUnresolved = BecomeParent(filterUnresolved);
			this.arguments = BecomeParent(arguments);
		}

		public override ICollection<BaseNode> Children
		{
			get
			{
				IList<BaseNode> children = new List<BaseNode>();
				children.Add(GetValidVersion(iteratedUnresolved, iterated));
				//children.add(methodIdent);	// HACK: We don't have a declaration, so avoid failure during check phase
				children.Add(arguments);
				return children;
			}
		}

		public override ICollection<string> ChildrenNames
		{
			get
			{
				IList<string> childrenNames = new List<string>();
				childrenNames.Add("iterated");
				//childrenNames.add("methodIdent");
				childrenNames.Add("params");
				return childrenNames;
			}
		}

		private static readonly DeclarationPairResolver<FilterAutoGeneratedDeclNode, FilterAutoSuppliedDeclNode> filterResolver =
				new DeclarationPairResolver<FilterAutoGeneratedDeclNode, FilterAutoSuppliedDeclNode>(typeof(FilterAutoGeneratedDeclNode), typeof(FilterAutoSuppliedDeclNode));

		protected internal override bool ResolveLocal()
		{
			// owner
			bool iteratedOk = base.ResolveLocal();
			if(!iteratedOk)
				return false;

			// member
			if(!(filterUnresolved is PackageIdentNode))
			{
				bool res = FixupDefinition(filterUnresolved, iterated.Scope);
				if(!res)
					return false;
			}
			Pair<FilterAutoGeneratedDeclNode, FilterAutoSuppliedDeclNode> filter = filterResolver.Resolve(filterUnresolved, this);
			if(filter == null)
				return false;
			filterAutoGenerated = filter.fst;
			filterAutoSupplied = filter.snd;
			return (filterAutoGenerated != null && filterAutoGenerated.Resolve())
					|| (filterAutoSupplied != null && filterAutoSupplied.Resolve());
		}

		protected internal override bool CheckLocal()
		{
			return true;
		}

		protected internal override IR ConstructIR()
		{
			FilterInvocation filterInvocation;
			if(filterAutoGenerated != null)
			{
				filterInvocation = new FilterInvocation(filterUnresolved.IRIdent.ToString(), filterUnresolved.IRIdent,
						filterAutoGenerated.CheckIR(typeof(FilterAutoGenerated)), iterated.CheckIR(typeof(Rule)));
			}
			else
			{
				filterInvocation = new FilterInvocation(filterUnresolved.IRIdent.ToString(), filterUnresolved.IRIdent,
						filterAutoSupplied.CheckIR(typeof(FilterAutoSupplied)), iterated.CheckIR(typeof(Rule)));
			}
			foreach(ExprNode expr in arguments.ChildrenExact)
			{
				ExprNode exprEvaluated = expr.Evaluate();
				filterInvocation.AddArgument(exprEvaluated.CheckIR(typeof(Expression)));
			}
			return filterInvocation;
		}
	}

}
