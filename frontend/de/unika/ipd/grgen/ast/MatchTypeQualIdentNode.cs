namespace de.unika.ipd.grgen.ast
{

using System.Collections.Generic;
using System.Diagnostics;

using MatchClassFilterAutoGeneratedDeclNode = de.unika.ipd.grgen.ast.decl.executable.MatchClassFilterAutoGeneratedDeclNode;
using MatchClassFilterFunctionDeclNode = de.unika.ipd.grgen.ast.decl.executable.MatchClassFilterFunctionDeclNode;
using DefinedMatchTypeNode = de.unika.ipd.grgen.ast.type.DefinedMatchTypeNode;
using de.unika.ipd.grgen.ast.util;
using de.unika.ipd.grgen.ast.util;
using de.unika.ipd.grgen.ast.util;
using Bad = de.unika.ipd.grgen.ir.Bad;
using IR = de.unika.ipd.grgen.ir.IR;
using Coords = de.unika.ipd.grgen.parser.Coords;

/// <summary>
/// AST node that represents a reference of a match class filter function to a match class
/// </summary>
public class MatchTypeQualIdentNode : BaseNode //implements DeclaredCharacter
{
	static MatchTypeQualIdentNode()
	{
		SetClassName(typeof(MatchTypeQualIdentNode), "match type qualified identifier");
	}

	protected internal IdentNode ownerUnresolved;
	private DefinedMatchTypeNode owner;

	protected internal IdentNode memberUnresolved;
	private MatchClassFilterCharacter member;

	public MatchTypeQualIdentNode(Coords coords, IdentNode owner, IdentNode member) : base(coords)
	{
		this.ownerUnresolved = owner;
		this.memberUnresolved = member;
	}

	/// <summary>
	/// returns children of this node </summary>
	public override ICollection<BaseNode> Children
	{
		get
		{
			IList<BaseNode> children = new List<BaseNode>();
			children.Add(GetValidVersion(ownerUnresolved, owner));
			children.Add(GetValidVersion(memberUnresolved, (BaseNode)member));
			return children;
		}
	}

	/// <summary>
	/// returns names of the children, same order as in getChildren </summary>
	public override ICollection<string> ChildrenNames
	{
		get
		{
			IList<string> childrenNames = new List<string>();
			childrenNames.Add("owner");
			childrenNames.Add("member");
			return childrenNames;
		}
	}

	public override string ToString()
	{
		return owner.Ident.ToString() + "." + member.FilterName;
	}

	private static readonly DeclarationTypeResolver<DefinedMatchTypeNode> ownerResolver
			= new DeclarationTypeResolver<DefinedMatchTypeNode>(typeof(DefinedMatchTypeNode));
	private static readonly DeclarationPairResolver<MatchClassFilterFunctionDeclNode, MatchClassFilterAutoGeneratedDeclNode> memberResolver
			= new DeclarationPairResolver<MatchClassFilterFunctionDeclNode, MatchClassFilterAutoGeneratedDeclNode>(
					typeof(MatchClassFilterFunctionDeclNode), typeof(MatchClassFilterAutoGeneratedDeclNode));

	/// <seealso cref="de.unika.ipd.grgen.ast.BaseNode.resolveLocal() "/>
	protected internal override bool ResolveLocal()
	{
		if(!(ownerUnresolved is PackageIdentNode))
			FixupDefinition(ownerUnresolved, ownerUnresolved.Scope);

		bool successfullyResolved = true;
		owner = ownerResolver.Resolve(ownerUnresolved, this);
		successfullyResolved = owner != null && successfullyResolved;
		bool ownerResolveResult = owner != null && owner.Resolve();

		if(!ownerResolveResult)
		{
			// "member" can not be resolved due to inaccessible owner
			ReportError("Left hand side " + ownerUnresolved + " of '.' is not a match class.");
			return false;
		}

		if(!(memberUnresolved is PackageIdentNode))
		{
			if(!TryFixupDefinition(memberUnresolved, owner.Scope.Parent))
				FixupDefinition(memberUnresolved, memberUnresolved.Scope);
		}
		Pair<MatchClassFilterFunctionDeclNode, MatchClassFilterAutoGeneratedDeclNode> resolved =
				memberResolver.Resolve(memberUnresolved, this);
		if(resolved == null)
		{
			memberUnresolved.ReportError("Call of unknown match class filter function "
					+ memberUnresolved + " (on " + owner.ToStringWithDeclarationCoords() + ").");
			return false;
		}
		if(resolved.fst != null)
			member = resolved.fst;
		else
			member = resolved.snd;

		return successfullyResolved;
	}

	/// <seealso cref="de.unika.ipd.grgen.ast.BaseNode.checkLocal() "/>
	protected internal override bool CheckLocal()
	{
		return true;
	}

	public virtual DefinedMatchTypeNode Owner
	{
		get
		{
			Debug.Assert(IsResolved());
			return owner;
		}
	}

	public virtual MatchClassFilterCharacter Member
	{
		get
		{
			Debug.Assert(IsResolved());
			return member;
		}
	}

	protected internal override IR ConstructIR()
	{
		Debug.Assert(false);
		return Bad.BadObject;
	}

	public static string KindStr
	{
		get
		{
			return "match class prefixed filter";
		}
	}
}

}
