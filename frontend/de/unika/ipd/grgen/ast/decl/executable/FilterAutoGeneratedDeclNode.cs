namespace de.unika.ipd.grgen.ast.decl.executable
{

using System.Collections.Generic;
using System.Text;

using BaseNode = de.unika.ipd.grgen.ast.BaseNode;
using FilterCharacter = de.unika.ipd.grgen.ast.FilterCharacter;
using IdentNode = de.unika.ipd.grgen.ast.IdentNode;
using DeclNode = de.unika.ipd.grgen.ast.decl.DeclNode;
using IteratedDeclNode = de.unika.ipd.grgen.ast.decl.pattern.IteratedDeclNode;
using TypeNode = de.unika.ipd.grgen.ast.type.TypeNode;
using de.unika.ipd.grgen.ast.util;
using de.unika.ipd.grgen.ast.util;
using IR = de.unika.ipd.grgen.ir.IR;
using FilterAutoGenerated = de.unika.ipd.grgen.ir.executable.FilterAutoGenerated;
using Rule = de.unika.ipd.grgen.ir.executable.Rule;

/// <summary>
/// AST node class representing auto-generated filters (generated upon declaration)
/// </summary>
public class FilterAutoGeneratedDeclNode : FilterAutoDeclNode, FilterCharacter
{
	static FilterAutoGeneratedDeclNode()
	{
		SetClassName(typeof(FilterAutoGeneratedDeclNode), "auto generated filter");
	}

	protected internal string name;
	protected internal List<string> entities; // null for auto, otherwise list with at least one element
	protected internal List<TypeNode> entityTypes;

	protected internal IdentNode actionUnresolved;
	protected internal ActionDeclNode action;
	protected internal IteratedDeclNode iterated;

	public FilterAutoGeneratedDeclNode(IdentNode ident, string name, List<string> entities, IdentNode action)
		: base(ident)
	{
		this.name = name;
		this.entities = entities;
		this.actionUnresolved = action;
	}

	/// <summary>
	/// returns children of this node </summary>
	public override ICollection<BaseNode> Children
	{
		get
		{
		IList<BaseNode> children = new List<BaseNode>();
		children.Add(GetValidVersion(actionUnresolved, action, iterated));
		return children;
		}
	}

	/// <summary>
	/// returns names of the children, same order as in getChildren </summary>
	public override ICollection<string> ChildrenNames
	{
		get
		{
		IList<string> childrenNames = new List<string>();
		childrenNames.Add("actionOrIterated");
		return childrenNames;
		}
	}

	private static readonly DeclarationPairResolver<ActionDeclNode, IteratedDeclNode> actionOrIteratedResolver =
			new DeclarationPairResolver<ActionDeclNode, IteratedDeclNode>(typeof(ActionDeclNode), typeof(IteratedDeclNode));

	/// <seealso cref="de.unika.ipd.grgen.ast.BaseNode.resolveLocal() "/>
	protected internal override bool ResolveLocal()
	{
		Pair<ActionDeclNode, IteratedDeclNode> actionOrIterated = actionOrIteratedResolver.Resolve(actionUnresolved, this);
		if(actionOrIterated == null)
			return false;
		action = actionOrIterated.fst;
		iterated = actionOrIterated.snd;
		return action != null || iterated != null;
	}

	/// <seealso cref="de.unika.ipd.grgen.ast.BaseNode.resolveLocal() "/>
	protected internal override bool CheckLocal()
	{
		if(entities == null)
		{
			if(!name.Equals("auto"))
			{
				ReportError("Unknown auto-generated filter " + name + " (only auto comes without parameters).");
				return false;
			}
			if(iterated != null)
			{
				ReportError("The auto filter is only available for rules/tests (not iterateds).");
				return false;
			}
			return true;
		}
		else
		{
			entityTypes = new List<TypeNode>();
			for(int i = 0; i < entities.Count; ++i)
			{
				if(name.Equals("keepOneForEachAccumulateBy") && i == entities.Count - 1)
					continue;

				string entity = entities[i];
				DeclNode resolvedEntity = action != null
						? action.pattern.TryGetMember(entity)
						: iterated.pattern.TryGetMember(entity);
				if(resolvedEntity == null)
				{
					ReportError("The entity " + entity
							+ " referenced in the filter declaration " + FilterNameWithEntitySuffix
							+ " is not known in the "
							+ (action != null ? action.Kind + " " + action.Ident : "iterated " + iterated.Ident) + ".");
					return false;
				}
				entityTypes.Add(resolvedEntity.DeclType);
			}
		}
		return true;
	}

	public virtual string FilterName
	{
		get
		{
		return name;
		}
	}

	public virtual string FilterNameWithEntitySuffix
	{
		get
		{
		StringBuilder sb = new StringBuilder();
		sb.Append(name);
		if(entities != null && entities.Count > 0)
		{
			sb.Append("<");
			bool first = true;
			foreach(string entity in entities)
			{
				if(first)
					first = false;
				else
					sb.Append(",");
				sb.Append(entity);
			}
			sb.Append(">");
		}
		return sb.ToString();
		}
	}

	public virtual ActionDeclNode Action
	{
		get
		{
		return action;
		}
	}

	public virtual IteratedDeclNode Iterated
	{
		get
		{
		return iterated;
		}
	}

	/// <summary>
	/// Returns the IR object for this autogen filter node. </summary>
	public virtual FilterAutoGenerated IRFilterAutoGenerated
	{
		get
		{
		return CheckIR(typeof(FilterAutoGenerated));
		}
	}

	protected internal override IR ConstructIR()
	{
		// return if the IR object was already constructed
		// that may happen in recursive calls
		if(IsIRAlreadySet())
			return IR;

		FilterAutoGenerated filterAutoGen = new FilterAutoGenerated(name, entities);

		// mark this node as already visited
		IR = filterAutoGen;

		Rule actionOrIterated = action != null ? action.IRMatcher : iterated.IRMatcher;
		filterAutoGen.Action = actionOrIterated;
		actionOrIterated.AddFilter(filterAutoGen);

		if(entityTypes != null)
		{
			foreach(TypeNode entityType in entityTypes)
				filterAutoGen.AddEntityType(entityType.IRType);
		}

		return filterAutoGen;
	}

	public static string KindStr
	{
		get
		{
		return "auto generated filter";
		}
	}
}

}
