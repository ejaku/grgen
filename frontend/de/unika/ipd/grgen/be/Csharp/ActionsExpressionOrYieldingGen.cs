		private void GenContainerAccumulationYield(SourceBuilder sb, ContainerAccumulationYield cay,
				string className, string pathPrefix, Dictionary<Entity, string> alreadyDefinedEntityToName)
		{
			Variable iterationVar = cay.IterationVar;
			Variable indexVar = cay.IndexVar;
			Variable container = cay.Container;

			sb.AppendFront("new GRGEN_EXPR.ContainerAccumulationYield(");
			sb.Append("\"" + FormatEntity(iterationVar, pathPrefix, alreadyDefinedEntityToName) + "\", ");
			sb.Append("\"" + FormatIdentifiable(iterationVar) + "\", ");
			Type valueType;
			Type indexType = null;
			if(container.Type is SetType)
			{
				valueType = ((SetType)container.Type).ValueType;
			}
			else if(container.Type is MapType)
			{
				valueType = ((MapType)container.Type).ValueType;
				indexType = ((MapType)container.Type).KeyType;
			}
			else if(container.Type is ArrayType)
			{
				valueType = ((ArrayType)container.Type).ValueType;
				indexType = IntType.Type;
