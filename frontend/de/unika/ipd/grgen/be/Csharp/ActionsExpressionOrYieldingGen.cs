		public virtual void GenYield(SourceBuilder sb, EvalStatement evalStmt, string className,
				string pathPrefix, Dictionary<Entity, string> alreadyDefinedEntityToName)
		{
			if(evalStmt is AssignmentVarIndexed) // must come before AssignmentVar
				GenAssignmentVarIndexed(sb, (AssignmentVarIndexed)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is AssignmentVar)
				GenAssignmentVar(sb, (AssignmentVar)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is AssignmentGraphEntity)
				GenAssignmentGraphEntity(sb, (AssignmentGraphEntity)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is AssignmentIdentical)
			{
				//nothing to generate, was assignment . = . optimized away;
			}
			else if(evalStmt is CompoundAssignmentVarChangedVar)
				GenCompoundAssignmentVarChangedVar(sb, (CompoundAssignmentVarChangedVar)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is CompoundAssignmentVar)
				GenCompoundAssignmentVar(sb, (CompoundAssignmentVar)evalStmt, "\t\t\t\t", className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is MapVarRemoveItem)
				GenMapVarRemoveItem(sb, (MapVarRemoveItem)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is MapVarClear)
				GenMapVarClear(sb, (MapVarClear)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is MapVarAddItem)
				GenMapVarAddItem(sb, (MapVarAddItem)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is SetVarRemoveItem)
				GenSetVarRemoveItem(sb, (SetVarRemoveItem)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is SetVarClear)
				GenSetVarClear(sb, (SetVarClear)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is SetVarAddItem)
				GenSetVarAddItem(sb, (SetVarAddItem)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is SetVarAddAll)
				GenSetVarAddAll(sb, (SetVarAddAll)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is ArrayVarRemoveItem)
				GenArrayVarRemoveItem(sb, (ArrayVarRemoveItem)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is ArrayVarClear)
				GenArrayVarClear(sb, (ArrayVarClear)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is ArrayVarAddItem)
				GenArrayVarAddItem(sb, (ArrayVarAddItem)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is ArrayVarAddAll)
				GenArrayVarAddAll(sb, (ArrayVarAddAll)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is DequeVarRemoveItem)
				GenDequeVarRemoveItem(sb, (DequeVarRemoveItem)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is DequeVarClear)
				GenDequeVarClear(sb, (DequeVarClear)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is DequeVarAddItem)
				GenDequeVarAddItem(sb, (DequeVarAddItem)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is IteratedAccumulationYield)
				GenIteratedAccumulationYield(sb, (IteratedAccumulationYield)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is ContainerAccumulationYield)
				GenContainerAccumulationYield(sb, (ContainerAccumulationYield)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is IntegerRangeIterationYield)
				GenIntegerRangeIterationYield(sb, (IntegerRangeIterationYield)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is ForFunction)
				GenForFunction(sb, (ForFunction)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is ForIndexAccessEquality)
				GenForIndexAccessEquality(sb, (ForIndexAccessEquality)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is ForIndexAccessOrdering)
				GenForIndexAccessOrdering(sb, (ForIndexAccessOrdering)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is ConditionStatement)
				GenConditionStatement(sb, (ConditionStatement)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is SwitchStatement)
				GenSwitchStatement(sb, (SwitchStatement)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is WhileStatement)
				GenWhileStatement(sb, (WhileStatement)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is DoWhileStatement)
				GenDoWhileStatement(sb, (DoWhileStatement)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is MultiStatement)
				GenMultiStatement(sb, (MultiStatement)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is DefDeclVarStatement)
				GenDefDeclVarStatement(sb, (DefDeclVarStatement)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is DefDeclGraphEntityStatement)
				GenDefDeclGraphEntityStatement(sb, (DefDeclGraphEntityStatement)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is BreakStatement)
				GenBreakStatement(sb, (BreakStatement)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is ContinueStatement)
				GenContinueStatement(sb, (ContinueStatement)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is EmitProc)
				GenEmitProc(sb, (EmitProc)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is AssertProc)
				GenAssertProc(sb, (AssertProc)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is DebugAddProc)
				GenDebugAddProc(sb, (DebugAddProc)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is DebugRemProc)
				GenDebugRemProc(sb, (DebugRemProc)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is DebugEmitProc)
				GenDebugEmitProc(sb, (DebugEmitProc)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is DebugHaltProc)
				GenDebugHaltProc(sb, (DebugHaltProc)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is DebugHighlightProc)
				GenDebugHighlightProc(sb, (DebugHighlightProc)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is RecordProc)
				GenRecordProc(sb, (RecordProc)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is ReturnAssignment)
				GenYield(sb, ((ReturnAssignment)evalStmt).ProcedureInvocation, className, pathPrefix, alreadyDefinedEntityToName);
			else if(evalStmt is IteratedFiltering)
				GenIteratedFiltering(sb, (IteratedFiltering)evalStmt, className, pathPrefix, alreadyDefinedEntityToName);
			else
				throw new System.NotSupportedException("Unexpected yield statement \"" + evalStmt + "\"");
		}

