		public virtual void GenExpressionTree(SourceBuilder sb, Expression expr, string className,
				string pathPrefix, Dictionary<Entity, string> alreadyDefinedEntityToName)
		{
			if(expr is Operator)
			{
				Operator op = (Operator)expr;
				string opNamePrefix = "";
				if(op.Type is SetType || op.Type is MapType)
					opNamePrefix = "DICT_";
				if(op.Type is ArrayType)
					opNamePrefix = "LIST_";
				if(op.Type is DequeType)
					opNamePrefix = "DEQUE_";
				if(op.OpCode == OperatorCode.EQ || op.OpCode == OperatorCode.NE
						|| op.OpCode == OperatorCode.SE
						|| op.OpCode == OperatorCode.GT || op.OpCode == OperatorCode.GE
						|| op.OpCode == OperatorCode.LT || op.OpCode == OperatorCode.LE)
				{
					Expression opnd = op.GetOperand(0); // or .getOperand(1), irrelevant
					if(opnd.Type is SetType || opnd.Type is MapType)
						opNamePrefix = "DICT_";
					if(opnd.Type is ArrayType)
						opNamePrefix = "LIST_";
					if(opnd.Type is DequeType)
						opNamePrefix = "DEQUE_";
					if(opnd.Type is GraphType)
						opNamePrefix = "GRAPH_";
					if(opnd.Type is InternalObjectType)
						opNamePrefix = "OBJECT_CLASS_";
					if(opnd.Type is InternalTransientObjectType)
						opNamePrefix = "TRANSIENT_OBJECT_CLASS_";
				}
				if(op.OpCode == OperatorCode.GT || op.OpCode == OperatorCode.GE
						|| op.OpCode == OperatorCode.LT || op.OpCode == OperatorCode.LE)
				{
					Expression opnd = op.GetOperand(0); // or .getOperand(1), irrelevant
					if(opnd.Type is StringType)
						opNamePrefix = "STRING_";
				}
				if(model.IsEqualClassDefined()
						&& (op.OpCode == OperatorCode.EQ || op.OpCode == OperatorCode.NE))
				{
					Expression opnd = op.GetOperand(0); // or .getOperand(1), irrelevant
					if(opnd.Type is ObjectType || opnd.Type is ExternalObjectType)
						opNamePrefix = "EXTERNAL_";
				}
				if(model.IsLowerClassDefined()
						&& (op.OpCode == OperatorCode.GT || op.OpCode == OperatorCode.GE
							|| op.OpCode == OperatorCode.LT || op.OpCode == OperatorCode.LE))
				{
					Expression opnd = op.GetOperand(0); // or .getOperand(1), irrelevant
					if(opnd.Type is ObjectType || opnd.Type is ExternalObjectType)
						opNamePrefix = "EXTERNAL_";
				}

