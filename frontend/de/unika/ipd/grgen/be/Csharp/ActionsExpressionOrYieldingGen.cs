			for(int i = 0; i < fi.FilterArguments.Count; ++i)
			{
				Expression argument = fi.GetFilterArgument(i);
				if(argument.Type is InheritanceType)
					sb.Append("\"" + FormatElementInterfaceRef(argument.Type) + "\"");
				else
					sb.Append("null");
				sb.Append(", ");
			}
			sb.Append("}");
			sb.Append(")");
		}

		private void GenFilterInvocationLambda(SourceBuilder sb, FilterInvocationLambdaExpression fi,
				string className, string pathPrefix, Dictionary<Entity, string> alreadyDefinedEntityToName)
		{
			sb.Append("new GRGEN_EXPR.FilterInvocationLambdaExpression(");
			sb.Append("\"" + fi.FilterName + "\", ");
			sb.Append((!string.ReferenceEquals(fi.FilterEntity, null) ? "\"" + fi.FilterEntity + "\"" : "null") + ", ");
			sb.Append((!string.ReferenceEquals(fi.FilterEntity, null) ? "\"" + FormatType(fi.FilterEntityType) + "\"" : "null") + ", ");
			sb.Append((fi.InitArrayAccessVariable != null ? "\"" + FormatEntity(fi.InitArrayAccessVariable, pathPrefix, alreadyDefinedEntityToName) + "\"" : "null") + ", ");
			Expression initExpression = fi.InitExpression;
			if(initExpression != null)
			{
				GenExpressionTree(sb, initExpression, className, pathPrefix, alreadyDefinedEntityToName);
				sb.Append(", ");
			}
			else
				sb.Append("null, ");
			sb.Append((fi.ArrayAccessVariable != null ? "\"" + FormatEntity(fi.ArrayAccessVariable, pathPrefix, alreadyDefinedEntityToName) + "\"" : "null") + ", ");
			sb.Append((fi.PreviousAccumulationAccessVariable != null ? "\"" + FormatEntity(fi.PreviousAccumulationAccessVariable, pathPrefix, alreadyDefinedEntityToName) + "\"" : "null") + ", ");
			sb.Append((fi.IndexVariable != null ? "\"" + FormatEntity(fi.IndexVariable, pathPrefix, alreadyDefinedEntityToName) + "\"" : "null") + ", ");
			sb.Append("\"" + FormatEntity(fi.ElementVariable, pathPrefix, alreadyDefinedEntityToName) + "\"" + ", ");
			Expression lambdaExpression = fi.LambdaExpression;
			GenExpressionTree(sb, lambdaExpression, className, pathPrefix, alreadyDefinedEntityToName);
			NeededEntities needs = new NeededEntities(Needs.NODES | Needs.EDGES | Needs.VARS | Needs.LAMBDAS);
			fi.CollectNeededEntities(needs);
			sb.Append(", new GRGEN_LGSP.PatternNode[] ");
			GenEntitySet(sb, needs.nodes, "", "", true, pathPrefix, alreadyDefinedEntityToName);
			sb.Append(", new GRGEN_LGSP.PatternEdge[] ");
			GenEntitySet(sb, needs.edges, "", "", true, pathPrefix, alreadyDefinedEntityToName);
			sb.Append(", new GRGEN_LGSP.PatternVariable[] ");
			GenEntitySet(sb, needs.variables, "", "", true, pathPrefix, alreadyDefinedEntityToName);
			sb.Append(")");
		}

