				switch(op.Arity())
				{
				case 1:
					GenExpressionTree(sb, op.GetOperand(0), className, pathPrefix, alreadyDefinedEntityToName);
					break;
				case 2:
					GenExpressionTree(sb, op.GetOperand(0), className, pathPrefix, alreadyDefinedEntityToName);
					sb.Append(", ");
					GenExpressionTree(sb, op.GetOperand(1), className, pathPrefix, alreadyDefinedEntityToName);
					if(op.OpCode == OperatorCode.IN)
					{
						if(op.GetOperand(0) is GraphEntityExpression)
							sb.Append(", \"" + FormatElementInterfaceRef(op.GetOperand(0).Type) + "\"");
						bool isDictionary = op.GetOperand(1).Type is SetType || op.GetOperand(1).Type is MapType;
						sb.Append(isDictionary ? ", true" : ", false");
					}
					else if(op.OpCode == OperatorCode.SE)
					{
						if(op.GetOperand(0).Type is ContainerType)
						{
							if(op.GetOperand(0).Type is SetType || op.GetOperand(0).Type is MapType)
							{
								bool isSet = op.GetOperand(0).Type is SetType;
								sb.Append(isSet ? ", true" : ", false");
							}
							bool isAttributeBearer = ((ContainerType)op.GetOperand(0).Type).ElementType is InheritanceType
									&& !(((ContainerType)op.GetOperand(0).Type).ElementType is ExternalObjectType);
							sb.Append(isAttributeBearer ? ", true" : ", false");
						}
					}
					break;
				case 3:
					if(op.OpCode == OperatorCode.COND)
					{
						GenExpressionTree(sb, op.GetOperand(0), className, pathPrefix, alreadyDefinedEntityToName);
						sb.Append(", ");
						GenExpressionTree(sb, op.GetOperand(1), className, pathPrefix, alreadyDefinedEntityToName);
						sb.Append(", ");
						GenExpressionTree(sb, op.GetOperand(2), className, pathPrefix, alreadyDefinedEntityToName);
						break;
					}
					goto default; //$FALL-THROUGH$
				default:
					throw new System.NotSupportedException("Unsupported operation arity (" + op.Arity() + ")");
				}
				sb.Append(")");
