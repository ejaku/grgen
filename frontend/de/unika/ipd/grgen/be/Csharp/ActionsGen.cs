		}

		private void GenPatternNode(SourceBuilder sb, SourceBuilder aux, PatternGraphLhs pattern, string pathPrefix,
				string patGraphVarName, string className, Dictionary<Entity, string> alreadyDefinedEntityToName,
				IList<Entity> parameters, double max, bool isMatchClass, string pathPrefixForElements,
				Node node, string nodeName)
		{
			sb.AppendFront((isMatchClass ? "static " : "") + "GRGEN_LGSP.PatternNode " + nodeName
					+ " = new GRGEN_LGSP.PatternNode(");
			sb.Append("(int) GRGEN_MODEL." + GetPackagePrefixDot(node.Type) + "NodeTypes.@"
					+ FormatIdentifiable(node.Type)
					+ ", " + FormatTypeClassRef(node.Type) + ".typeVar"
					+ ", \"" + FormatElementInterfaceRef(node.Type) + "\", ");
			sb.Append("\"" + nodeName + "\", \"" + FormatIdentifiable(node) + "\", ");
			sb.Append(nodeName + "_AllowedTypes, ");
			sb.Append(nodeName + "_IsAllowedType, ");
			AppendPrio(sb, node, max);
			sb.Append(parameters.IndexOf(node) + ", ");
			sb.Append(node.MaybeNull ? "true, " : "false, ");
			GenStorageAccess(sb, pathPrefix, alreadyDefinedEntityToName, pathPrefixForElements, node);
			GenIndexAccess(sb, pathPrefix, className, alreadyDefinedEntityToName, pathPrefixForElements, node, parameters);
			GenNameLookup(sb, pathPrefix, className, alreadyDefinedEntityToName, pathPrefixForElements, node, parameters);
			GenUniqueLookup(sb, pathPrefix, className, alreadyDefinedEntityToName, pathPrefixForElements, node, parameters);
			sb.Append((node is RetypedNode
					? FormatEntity(((RetypedNode)node).OldNode, pathPrefixForElements, alreadyDefinedEntityToName)
					: "null") + ", ");
			sb.Append(node.IsDefToBeYieldedTo() ? "true," : "false,");
