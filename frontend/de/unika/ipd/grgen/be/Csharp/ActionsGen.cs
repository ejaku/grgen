			GenStorageAccess(sb, pathPrefix, alreadyDefinedEntityToName, pathPrefixForElements, edge);
			GenIndexAccess(sb, pathPrefix, className, alreadyDefinedEntityToName, pathPrefixForElements, edge, parameters);
			GenNameLookup(sb, pathPrefix, className, alreadyDefinedEntityToName, pathPrefixForElements, edge, parameters);
			GenUniqueLookup(sb, pathPrefix, className, alreadyDefinedEntityToName, pathPrefixForElements, edge, parameters);
			sb.Append((edge is RetypedEdge
