		private void GenAllowedNodeTypeArrays(SourceBuilder sb, PatternGraphLhs pattern,
				string pathPrefixForElements, Dictionary<Entity, string> alreadyDefinedEntityToName)
		{
			SourceBuilder aux = new SourceBuilder();
			aux.IndentationLevel = sb.IndentationLevel;

			foreach(Node node in pattern.Nodes)
			{
				if(!string.ReferenceEquals(alreadyDefinedEntityToName[node], null))
					continue;
				sb.AppendFront("public static GRGEN_LIBGR.NodeType[] "
						+ FormatEntity(node, pathPrefixForElements) + "_AllowedTypes = ");
				aux.AppendFront("public static bool[] " + FormatEntity(node, pathPrefixForElements) + "_IsAllowedType = ");
				if(node.GetConstraints().Count > 0)
				{
					// alle verbotenen Typen und deren Untertypen
					HashSet<Type> allForbiddenTypes = new HashSet<Type>();
					foreach(Type forbiddenType in node.GetConstraints())
					{
						foreach(Type type in model.AllNodeTypes)
						{
							if(type.IsCastableTo(forbiddenType))
								allForbiddenTypes.Add(type);
						}
					}
					sb.Append("{ ");
					aux.Append("{ ");
					foreach(Type type in model.AllNodeTypes)
					{
						bool isAllowed = type.IsCastableTo(node.NodeType) && !allForbiddenTypes.Contains(type);
						// all permitted nodes, aka nodes that are not forbidden
						if(isAllowed)
							sb.Append(FormatTypeClassRef(type) + ".typeVar, ");
						aux.Append(isAllowed);
						aux.Append(", ");
					}
					sb.Append("}");
					aux.Append("}");
				}
				else
				{
					sb.Append("null");
					aux.Append("null");
				}
				sb.Append(";\n");
				aux.Append(";\n");
				alreadyDefinedEntityToName[node] = FormatEntity(node, pathPrefixForElements);
			}

			sb.Append(aux.ToString());
		}

