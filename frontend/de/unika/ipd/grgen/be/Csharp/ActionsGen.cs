		private double ComputePriosMax(double max, PatternGraphLhs pattern)
		{
			max = ComputePriosMax(pattern.Nodes, max);
			max = ComputePriosMax(pattern.Edges, max);
			foreach(PatternGraphLhs neg in pattern.Negs)
				max = ComputePriosMax(max, neg);
			foreach(PatternGraphLhs idpt in pattern.Idpts)
				max = ComputePriosMax(max, idpt);
			foreach(Alternative alt in pattern.Alts)
			{
				foreach(Rule altCase in alt.AlternativeCases)
				{
					PatternGraphLhs altCasePattern = altCase.Left;
					max = ComputePriosMax(max, altCasePattern);
				}
			}
			foreach(Rule iter in pattern.Iters)
			{
				PatternGraphLhs iterPattern = iter.Left;
				max = ComputePriosMax(max, iterPattern);
			}
			return max;
		}

		private static double ComputePriosMax<T1>(ICollection<T1> nodesOrEdges, double max) where T1 : Entity
		{
			foreach(Entity noe in nodesOrEdges)
			{
				object prioO = noe.Annotations.Get("prio");

				if(prioO != null && prioO is int?)
				{
					double val = ((int?)prioO).Value;
					Debug.Assert(val > 0, "value of prio attribute of decl is out of range.");

					if(max < val)
						max = val;
				}
			}
			return max;
		}

		private static void AppendPrio(SourceBuilder sb, Entity entity, double max)
		{
			object prioO = entity.Annotations.Get("prio");

			double prio;
			if(prioO != null && prioO is int?)
			{
				prio = ((int?)prioO).Value;
				prio = 10.0 - (prio / max) * 9.0;
			}
			else
				prio = 5.5;

			sb.Append(prio + "F, ");
		}

