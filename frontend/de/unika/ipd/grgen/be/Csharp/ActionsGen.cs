		/// <summary>
		/// Generates the match classes (of pattern and contained patterns)
		/// </summary>
		private void GenMatch(SourceBuilder sb, PatternGraphLhs pattern, ICollection<DefinedMatchType> implementedMatchClasses,
				string className, bool parallelized)
		{
			HashSet<string> elementsAlreadyDeclared = new HashSet<string>();
			string @base = "";
			if(implementedMatchClasses == null || implementedMatchClasses.Count == 0)
				@base = "GRGEN_LIBGR.IMatch";
			else
			{
				bool first = true;
				foreach(DefinedMatchType implementedMatchClass in implementedMatchClasses)
				{
					foreach(Node node in implementedMatchClass.Nodes)
						elementsAlreadyDeclared.Add(FormatEntity(node));
					foreach(Edge edge in implementedMatchClass.Edges)
						elementsAlreadyDeclared.Add(FormatEntity(edge));
					foreach(Variable var in implementedMatchClass.Vars)
						elementsAlreadyDeclared.Add(FormatEntity(var));
					if(first)
						first = false;
					else
						@base += ", ";
					string packagePrefix = !string.ReferenceEquals(implementedMatchClass.PackageContainedIn, null)
							? implementedMatchClass.PackageContainedIn + "."
							: "";
					@base += packagePrefix + "IMatch_" + implementedMatchClass.Name;
				}
			}

			// generate getters to contained nodes, edges, variables, embedded graphs, alternatives
			ActionsMatchGen matchGen = new ActionsMatchGen(nodeTypePrefix, edgeTypePrefix, objectTypePrefix, transientObjectTypePrefix);
			matchGen.GenPatternMatchInterface(sb, pattern, pattern.NameOfGraph,
					@base, pattern.NameOfGraph + "_",
					false, false, false, elementsAlreadyDeclared);

			// generate contained nodes, edges, variables, embedded graphs, alternatives
			// and the implementation of the various getters from IMatch and the pattern specific match interface
			string patGraphVarName = "pat_" + pattern.NameOfGraph;
			matchGen.GenPatternMatchImplementation(sb, pattern, pattern.NameOfGraph,
					patGraphVarName, className, pattern.NameOfGraph + "_", false, false, parallelized, false);
		}

