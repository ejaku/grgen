		private void GenArgumentCasting(SourceBuilder sb, Entity inParam, int argumentNumber)
		{
			if(inParam.Type.IsArrayOfMatchType())
			{
				ArrayType arrayType = (ArrayType)inParam.Type;
				MatchType matchType = (MatchType)arrayType.ValueType;
				string packagePrefixOfAction = "GRGEN_ACTIONS." + GetPackagePrefixDot(matchType.Action);
				string actionName = matchType.Action.GetIdent().ToString();
				string ruleClass = packagePrefixOfAction + "Rule_" + actionName;
				sb.Append(", " + ruleClass + ".ConvertAsNeeded(arguments[" + argumentNumber + "])");
			}
			else if(inParam.Type.IsArrayOfMatchClassType())
			{
				ArrayType arrayType = (ArrayType)inParam.Type;
				DefinedMatchType matchType = (DefinedMatchType)arrayType.ValueType;
				string packagePrefixOfMatchClass = "GRGEN_ACTIONS." + GetPackagePrefixDot(matchType);
				string matchClassName = matchType.Ident.ToString();
				string matchClass = packagePrefixOfMatchClass + "MatchClassInfo_" + matchClassName;
				sb.Append(", " + matchClass + ".ConvertAsNeeded(arguments[" + argumentNumber + "])");
			}
			else
				sb.Append(", (" + FormatType(inParam.Type) + ")arguments[" + argumentNumber + "]");
		}

