namespace de.unika.ipd.grgen.ir.executable
{

using System.Collections.Generic;
using System.Text;

using IR = de.unika.ipd.grgen.ir.IR;
using Type = de.unika.ipd.grgen.ir.type.Type;

/// <summary>
/// An auto-generated filter.
/// </summary>
public class FilterAutoGenerated : IR, Filter
{
	protected internal string name;
	protected internal List<string> entities;
	protected internal List<Type> entityTypes;

	/// <summary>
	/// The action we're a filter for </summary>
	protected internal Rule action;

	public FilterAutoGenerated(string name, List<string> entities)
		: base(name)
	{
		this.name = name;
		this.entities = entities;
		if(entities != null)
			this.entityTypes = new List<Type>();
	}

	public virtual Rule Action
	{
		set
		{
			this.action = value;
		}
		get
		{
			return action;
		}
	}

	public virtual void AddEntityType(Type entityType)
	{
		this.entityTypes.Add(entityType);
	}


	public virtual string FilterName
	{
		get
		{
			return name;
		}
	}

	public virtual List<string> FilterEntities
	{
		get
		{
			return entities;
		}
	}

	public virtual List<Type> FilterEntityTypes
	{
		get
		{
			return entityTypes;
		}
	}

	public virtual string Suffix
	{
		get
		{
			StringBuilder sb = new StringBuilder();
			if(entities != null && entities.Count != 0 && !string.ReferenceEquals(name, "auto"))
			{
				sb.Append("<");
				bool first = true;
				foreach(string entity in entities)
				{
					if(first)
						first = false;
					else
						sb.Append(",");
					sb.Append(entity);
				}
				sb.Append(">");
			}
			return sb.ToString();
		}
	}

	public virtual string UnderscoreSuffix
	{
		get
		{
			StringBuilder sb = new StringBuilder();
			if(entities != null && entities.Count != 0 && !string.ReferenceEquals(name, "auto"))
			{
				foreach(string entity in entities)
				{
					sb.Append("_");
					sb.Append(entity);
				}
			}
			return sb.ToString();
		}
	}
}

}
