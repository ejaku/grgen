namespace de.unika.ipd.grgen.ir.executable
{

using System.Collections.Generic;
using System.Text;

using IR = de.unika.ipd.grgen.ir.IR;
using DefinedMatchType = de.unika.ipd.grgen.ir.type.DefinedMatchType;
using Type = de.unika.ipd.grgen.ir.type.Type;

/// <summary>
/// An auto-generated match class filter.
/// </summary>
public class MatchClassFilterAutoGenerated : IR, MatchClassFilter
{
	protected internal string name;
	protected internal List<string> entities;
	protected internal List<Type> entityTypes;

	/// <summary>
	/// The match class we're a filter for </summary>
	protected internal DefinedMatchType matchClass;

	public MatchClassFilterAutoGenerated(string name, List<string> entities)
		: base(name)
	{
		this.name = name;
		this.entities = entities;
		if(entities != null)
			this.entityTypes = new List<Type>();
	}

	public virtual DefinedMatchType MatchClass
	{
		set
		{
		this.matchClass = value;
		}
		get
		{
		return matchClass;
		}
	}

	public virtual void AddEntityType(Type entityType)
	{
		this.entityTypes.Add(entityType);
	}


	public virtual string FilterName
	{
		get
		{
		return name;
		}
	}

	public virtual List<string> FilterEntities
	{
		get
		{
		return entities;
		}
	}

	public virtual List<Type> FilterEntityTypes
	{
		get
		{
		return entityTypes;
		}
	}

	public virtual string Suffix
	{
		get
		{
		StringBuilder sb = new StringBuilder();
		if(entities != null && entities.Count != 0 && !string.ReferenceEquals(name, "auto"))
		{
			sb.Append("<");
			bool first = true;
			foreach(string entity in entities)
			{
				if(first)
					first = false;
				else
					sb.Append(",");
				sb.Append(entity);
			}
			sb.Append(">");
		}
		return sb.ToString();
		}
	}
}

}
